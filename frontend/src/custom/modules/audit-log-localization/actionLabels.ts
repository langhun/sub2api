function formatDerivedAction(action: string): string | undefined {
  const parts = action.split('.').filter(Boolean)
  if (parts.length < 2) return undefined

  const verb = parts[parts.length - 1]
  if (!verb || !verbLabels[verb]) return undefined
  const resource = parts
    .slice(0, -1)
    .filter((part) => part !== 'admin' && part !== 'custom')
    .map((part) => resourceLabels[part])
  if (resource.some((part) => !part)) return undefined

  return `${verbLabels[verb]}${resource.join('')}`
}

/**
 * Converts the stable audit action identifier into an operator-facing Chinese
 * description without changing the identifier used by filtering or storage.
 */
export function formatAuditAction(action: string): AuditActionDisplay {
  const normalized = action.trim()
  if (!normalized) return { label: '未识别操作' }
  const label = exactLabels[normalized] ?? formatDerivedAction(normalized)
  return label ? { label } : { label: '未识别操作', title: normalized }
}
